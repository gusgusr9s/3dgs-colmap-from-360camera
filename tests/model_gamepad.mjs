import assert from 'node:assert/strict';
import { GamepadInput, stickInput } from '../assets/app/model_gamepad.mjs';

const pad = (index = 0) => ({ id: 'Xbox Wireless Controller', index, connected: true, mapping: 'standard',
  axes: [0,0,0,0], buttons: Array.from({ length: 17 }, () => ({ value: 0, pressed: false })) });
assert.deepEqual(stickInput(.07, -.09), { x: 0, y: 0 }, 'Small two-axis stick drift stays still');
assert.ok(Math.abs(stickInput(.575,0).x - .5) < 1e-12, 'Half stick strength is preserved after the dead zone');
assert.ok(Math.abs(Math.hypot(...Object.values(stickInput(1,1))) - 1) < 1e-12, 'Diagonal input cannot exceed full strength');
assert.deepEqual(stickInput(NaN,Infinity), { x: 0, y: 0 });
const reader = new GamepadInput();
const xbox = pad(2);
assert.equal(reader.read([null,null,xbox], true).state, 'active', 'Sparse gamepad slots work');
xbox.axes = [.575,-.575,.5,-.5];
xbox.buttons[7] = { value: .525, pressed: true };
xbox.buttons[10] = { value: 1, pressed: true };
let sample = reader.read([null,null,xbox], true);
assert.ok(sample.movement.forward > 0 && sample.movement.right > 0);
assert.equal(sample.movement.sprint, true);
assert.ok(Math.abs(sample.movement.up - .5) < 1e-12, 'RT supports analog ascent');
assert.ok(sample.look.x > 0 && sample.look.y < 0);
xbox.buttons[0] = { value: 1, pressed: true };
assert.ok(reader.read([xbox],true).pressed.has(0));
assert.equal(reader.read([xbox],true).pressed.has(0), false, 'Holding a mode button only changes mode once');
assert.equal(reader.read([xbox],false).state, 'paused');
assert.equal(reader.read([xbox],true).state, 'release', 'Held sticks/buttons cannot resume after losing focus');
const neutral = pad(2);
assert.equal(reader.read([neutral],true).state, 'active');
neutral.axes[1] = -1;
assert.equal(reader.read([neutral],true).movement.forward, 1);
assert.equal(reader.read([],true).state, 'waiting', 'Disconnect immediately clears input');
assert.equal(reader.read([neutral],true).state, 'release', 'Reconnect needs neutral input');
neutral.axes[1] = 0;
reader.read([neutral],true);
const second = pad(0);
assert.equal(reader.read([second,neutral],true).pad.index, 2, 'A second controller does not steal control');
neutral.connected = false;
assert.equal(reader.read([second,neutral],true).pad.index, 0, 'A remaining controller can take over after release');
assert.equal(reader.read([{...pad(),mapping:''}],true).state, 'unsupported', 'Unknown layouts are not silently mapped');
console.log('Gamepad input passed: drift, analog strength, diagonal limits, triggers, edge buttons, sparse slots, pause, reconnect and controller selection.');
